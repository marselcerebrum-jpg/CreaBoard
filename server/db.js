const toPositional = (sql) => {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
};

const noNested = () => {
  throw new Error("nested transaction");
};

/** Membungkus objek yang punya query(text, params) → { rows, rowCount | affectedRows }. */
function wrap(runner, txImpl) {
  const db = {
    async query(sql, params = []) {
      return (await runner.query(toPositional(sql), params)).rows;
    },
    async one(sql, params = []) {
      return (await db.query(sql, params))[0] ?? null;
    },
    async run(sql, params = []) {
      const r = await runner.query(toPositional(sql), params);
      return r.rowCount ?? r.affectedRows ?? 0;
    },
    async exec(sql) {
      if (runner.exec) await runner.exec(sql);
      else await runner.query(sql);
    },
    tx: txImpl,
  };
  return db;
}

/** Produksi: pool node-postgres. Setiap transaksi memakai satu koneksi khusus. */
export function fromPool(pool) {
  return wrap(pool, async (fn) => {
    const client = await pool.connect();
    try {
      await client.query("begin");
      const out = await fn(wrap(client, noNested));
      await client.query("commit");
      return out;
    } catch (e) {
      await client.query("rollback").catch(() => {});
      throw e;
    } finally {
      client.release();
    }
  });
}

/** Tes: PGlite (satu koneksi, transaksi bawaan). */
export function fromPglite(pglite) {
  return wrap(pglite, (fn) => pglite.transaction((t) => fn(wrap(t, noNested))));
}

/** Membuat tabel (idempoten) dan mengisi pilihan dropdown bawaan. */
export async function migrate(db) {
  await db.exec(SCHEMA);
  // Pembagian apps hanya berlaku untuk staff Marketing.
  await db.run("delete from user_apps where user_id in (select id from users where role <> 'Marketing' or position <> 'Staff')");
  await db.run("update options set category = label where category is null");
  const { n } = await db.one("select count(*)::int n from options");
  if (n === 0) {
    for (const [key, list] of Object.entries(DEFAULT_OPTIONS)) {
      for (const [i, [label, semantic]] of list.entries()) {
        await db.run("insert into options (id, key, label, semantic, sort, category) values (?, ?, ?, ?, ?, ?)", [`${key}:${i + 1}`, key, label, semantic, i, label]);
      }
    }
  }
  return db;
}
